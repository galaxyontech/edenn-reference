/** Regional-indicator pair. Renders as a flag everywhere except Windows, which
 *  shows the two letters instead — still the right answer, just less pretty. */
export function flagOf(code) {
  return String.fromCodePoint(
    ...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

export const DEFAULT_COUNTRY = 'CN';

export const byCode = (code) =>
  COUNTRIES.find((country) => country.c === code) || null;

/**
 * Longest dial code matching a pasted E.164 number, and the rest of it.
 * Longest-first because "+1" prefixes "+1345" and "+44" prefixes "+441481":
 * matching the short one would leave the area code inside the local number.
 */
export function splitE164(raw) {
  const digits = String(raw || '').replace(/\D/g, '');
  if (!digits) return null;
  let best = null;
  for (const country of COUNTRIES) {
    if (!digits.startsWith(country.d)) continue;
    if (!best || country.d.length > best.d.length) best = country;
  }
  return best ? { country: best, national: digits.slice(best.d.length) } : null;
}
